/// 4 个 `SOURCE_*` 常量的**取值**逐条钉住（登记表里用的是字面量，因此这一条与
/// 上面那张表互补：表钉"每条用了哪个值"，本条钉"这些值本身是什么"）。
#[test]
fn source_constants_are_pinned_to_their_documented_values() {
    let sources: [&str; 4] = [
        SOURCE_TRADITIONAL_THEORY,
        SOURCE_COMMON_PRACTICE,
        SOURCE_20C_COMMERCIAL_PRACTICE,
        SOURCE_YEBAN_ORIGINAL,
    ];
    assert_eq!(
        sources,
        [
            "traditional-theory/public-domain",
            "common-practice/public-domain",
            "20c-commercial-practice-facts",
            "yeban-original-encoding",
        ]
    );
    // 四个取值两两不同（`source_histogram` 的键因此无歧义）。
    for (i, a) in sources.iter().enumerate() {
        for b in &sources[i + 1..] {
            assert_ne!(a, b);
        }
    }
}
