/// R48 两半：`arm` 无通配臂（新增变体 ⇒ `error[E0004]` 编译失败）；
/// 清单经 `arm` 映射后必须恰为 `0..N`（缺一臂或有重复 ⇒ 运行时红）。
#[test]
fn enum_arm_tables_are_exhaustive_and_gap_free() {
    let arms: Vec<u8> = ALL_CHORD_KINDS.iter().map(|k| chord_kind_arm(*k)).collect();
    assert_eq!(arms, (0..21).collect::<Vec<u8>>(), "ChordKind arms");
    let arms: Vec<u8> = ALL_TONALITIES.iter().map(|t| tonality_arm(*t)).collect();
    assert_eq!(arms, (0..3).collect::<Vec<u8>>(), "Tonality arms");
    let arms: Vec<u8> = ALL_SCALE_KINDS.iter().map(|k| scale_kind_arm(*k)).collect();
    assert_eq!(arms, (0..16).collect::<Vec<u8>>(), "ScaleKind arms");
    let arms: Vec<u8> = ALL_ROMAN_QUALITIES
        .iter()
        .map(|q| roman_quality_arm(*q))
        .collect();
    assert_eq!(arms, (0..5).collect::<Vec<u8>>(), "RomanQuality arms");
    let arms: Vec<u8> = ALL_DRUM_VOICES.iter().map(|v| drum_voice_arm(*v)).collect();
    assert_eq!(arms, (0..4).collect::<Vec<u8>>(), "DrumVoice arms");
    let arms: Vec<u8> = ALL_DRUM_STYLES.iter().map(|s| drum_style_arm(*s)).collect();
    assert_eq!(arms, (0..2).collect::<Vec<u8>>(), "DrumStyle arms");
    // 清单长度必须等于臂数（表本身也要与臂一一对应）。
    assert_eq!(ALL_CHORD_KINDS.len(), 21);
    assert_eq!(ALL_SCALE_KINDS.len(), 16);
    assert_eq!(ALL_DRUM_VOICES.len(), DRUM_VOICE_COUNT);
}

